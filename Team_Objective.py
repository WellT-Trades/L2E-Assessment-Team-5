'''
Project brief

These briefs are for beginner developers working in teams. The goal is
To deliver a small but complete, working product in seven days---not a production-scale platform. Shared rules for every project

Recommended team size: 4--6 people. Assign each person clear ownership of a component or workflow.

Day 1: Agree on the MVP, user stories, data model, API contracts, Git workflow, and task owners.

Days 2--3: Build components in parallel. Use mocks when another component is not ready.

Day 4: Integrate the components and stop adding major features.

Day 5: Test edge cases, fix bugs, and review security.

Day 6: Deploy the demo and finish the README.

Day 7: Present the product, explain technical decisions, and complete a team retrospective.

Use Git branches and pull requests; do not push directly to main.

Never commit credentials. Use synthetic data. Do not run untrusted code or test systems without permission.

Optional features must not jeopardize the minimum viable product (MVP).

Judging rubric --- 100 points Criterion Points What judges look for Core functionality 25 The required MVP works end-to-end; features shown in slides but not working do not count.

Engineering and 20 Appropriate data correctness modeling, clear module boundaries, validation, and useful error handling.

Testing and 15 Meaningful automated reliability tests and evidence that important edge cases were considered.

Collaboration and Git 15 Clear ownership, workflow understandable commits, pull requests, code reviews, and successful integration.

Usability and demo 10 Reviewers can understand and use the product without extensive help.

Documentation and 10 Useful README, setup setup steps, sample data, architecture notes, and known limitations.

Scope and delivery 5 The team prioritized well and delivered within the one-week timebox. Judging safeguards

A smaller, complete, tested MVP should score higher than a broad but broken implementation.

Each participant must explain their contribution and one technical decision during the demo.

Teams must disclose borrowed code, libraries, templates, and code-generation tools, and be able to explain what they submit.

Judges should consider whether the team handled the project's stated constraints safely.

Teams should identify unfinished work honestly; do not present mock functionality as a completed feature.'''